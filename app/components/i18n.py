def get_lang() -> str:
    if "lang" not in st.session_state:
        st.session_state["lang"] = "es"
    return st.session_state["lang"]

def t(key: str, default: str = None) -> str:
    lang = get_lang()
    # Check if translation exists, otherwise return default or key
    val = TRANSLATIONS.get(lang, {}).get(key, default)
    if val is None:
        # Check standard case-insensitive mapping
        val = TRANSLATIONS.get(lang, {}).get(key.strip(), default or key)
    return val
